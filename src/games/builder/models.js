export function modelParts(type, level = 1) {
  let key = type;
  if (type === 'house') key = 'house' + Math.max(1, Math.min(3, level));
  const fn = MODELS[key] || MODELS.house1;
  const parts = fn();
  if (type !== 'house' && type !== 'townhall' && level >= 2) parts.push(...PENNANT);
  return parts;
}

